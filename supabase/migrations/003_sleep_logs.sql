CREATE TABLE IF NOT EXISTS public.sleep_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    source          TEXT DEFAULT 'apple_health', -- 'apple_health' | 'telegram' | 'manual'

    -- Sleep timing
    sleep_date      DATE NOT NULL,          -- date of the NIGHT (e.g., night of Oct 16th = '2026-10-16')

    -- Duration metrics (from Apple Health sleep phases)
    total_hours     NUMERIC,                -- total time in bed or asleep
    deep_hours      NUMERIC,               -- deep sleep (HKCategoryValueSleepAnalysisAsleepDeep)
    rem_hours       NUMERIC,               -- REM phase
    core_hours      NUMERIC,               -- light/core sleep
    awake_hours     NUMERIC,               -- time awake in bed

    -- Recovery biomarkers (captured next morning by Apple Watch)
    hrv_avg_ms      NUMERIC,               -- HRV SDNN averaged over the night (ms)
    rhr_bpm         NUMERIC,               -- resting heart rate measured at wake-up (bpm)
    vo2max          NUMERIC,               -- VO2Max estimate if Apple Watch updated it

    created_at      TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,

    UNIQUE (user_id, sleep_date)           -- one sleep record per night per user
);

CREATE INDEX IF NOT EXISTS idx_sleep_logs_user_date ON public.sleep_logs(user_id, sleep_date DESC);
