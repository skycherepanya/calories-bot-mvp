CREATE TABLE IF NOT EXISTS public.workouts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,

    -- Activity classification
    workout_type    TEXT NOT NULL,          -- 'running' | 'strength' | 'cycling' | 'walking' | 'other'
    source          TEXT DEFAULT 'manual',  -- 'apple_health' | 'strava' | 'telegram' | 'manual'

    -- Timing
    started_at      TIMESTAMPTZ NOT NULL,
    duration_min    NUMERIC NOT NULL,
    dietary_date    DATE NOT NULL,          -- same 4-hour shift rule as meals

    -- Performance metrics
    distance_km     NUMERIC,               -- for cardio workouts
    avg_heart_rate  NUMERIC,               -- bpm
    max_heart_rate  NUMERIC,               -- bpm
    active_kcal     NUMERIC,               -- calories burned during workout
    avg_pace_min_km NUMERIC,               -- min/km (running/cycling only)
    elevation_m     NUMERIC,               -- elevation gain in meters

    -- Recovery context
    notes           TEXT,                  -- optional user note or AI summary
    raw_data        JSONB DEFAULT '{}',    -- original payload from Strava/Apple Health for future re-processing

    created_at      TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_workouts_user_date ON public.workouts(user_id, dietary_date);
CREATE INDEX IF NOT EXISTS idx_workouts_started_at ON public.workouts(user_id, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_workouts_type ON public.workouts(user_id, workout_type);
