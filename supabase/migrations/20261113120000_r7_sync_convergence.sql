-- 1. Reconcile daily_metrics bootstrap so out-of-order replays cannot fail (Audit F28)
CREATE TABLE IF NOT EXISTS public.daily_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    metric_date DATE NOT NULL,
    morning_weight_kg NUMERIC,
    body_fat_pct NUMERIC,
    water_pct NUMERIC,
    sleep_hours NUMERIC,
    deep_sleep_hours NUMERIC,
    rem_sleep_hours NUMERIC,
    resting_hr NUMERIC,
    hrv_ms NUMERIC,
    steps INTEGER,
    active_kcal NUMERIC,
    distance_km NUMERIC,
    source TEXT DEFAULT 'apple_health',
    neat_kcal NUMERIC(6, 1),
    rolling_avg_weight_7d NUMERIC,
    rolling_avg_weight_14d NUMERIC,
    trimp_score NUMERIC(6, 1),
    ewma_acute_load NUMERIC(6, 1),
    ewma_chronic_load NUMERIC(6, 1),
    acwr_ratio NUMERIC(4, 2),
    body_battery_wake INTEGER,
    body_battery_min INTEGER,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(user_id, metric_date)
);

ALTER TABLE public.daily_metrics
    ADD COLUMN IF NOT EXISTS distance_km NUMERIC,
    ADD COLUMN IF NOT EXISTS source TEXT DEFAULT 'apple_health',
    ADD COLUMN IF NOT EXISTS neat_kcal NUMERIC(6, 1),
    ADD COLUMN IF NOT EXISTS trimp_score NUMERIC(6, 1),
    ADD COLUMN IF NOT EXISTS ewma_acute_load NUMERIC(6, 1),
    ADD COLUMN IF NOT EXISTS ewma_chronic_load NUMERIC(6, 1),
    ADD COLUMN IF NOT EXISTS acwr_ratio NUMERIC(4, 2),
    ADD COLUMN IF NOT EXISTS body_battery_wake INTEGER,
    ADD COLUMN IF NOT EXISTS body_battery_min INTEGER;

CREATE INDEX IF NOT EXISTS idx_daily_metrics_date ON public.daily_metrics(user_id, metric_date);
CREATE INDEX IF NOT EXISTS idx_daily_metrics_user_date ON public.daily_metrics(user_id, metric_date DESC);

-- 2. Alter public.meals for nullable weight_g (Audit F23) and convergence columns
ALTER TABLE public.meals
    ALTER COLUMN weight_g DROP NOT NULL;

ALTER TABLE public.meals
    ADD COLUMN IF NOT EXISTS client_uuid UUID,
    ADD COLUMN IF NOT EXISTS revision INTEGER NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS kcal_exact NUMERIC,
    ADD COLUMN IF NOT EXISTS buffer_version INTEGER NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS provenance TEXT NOT NULL DEFAULT 'legacy',
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now());

CREATE UNIQUE INDEX IF NOT EXISTS idx_meals_user_client_uuid
    ON public.meals(user_id, client_uuid)
    WHERE client_uuid IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_meals_user_updated_at
    ON public.meals(user_id, updated_at DESC);

-- 3. Alter public.workout_analyses for CAS revision tracking
ALTER TABLE public.workout_analyses
    ADD COLUMN IF NOT EXISTS revision INTEGER NOT NULL DEFAULT 1;
